import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createClient} from '@supabase/supabase-js';
import {resolveEnvironment} from '../src/environment.js';
import {createSharedTestFetch,isTestCard} from '../src/sharedTest.js';
import {assignPreparedRoute} from '../src/services/routeAssignment.js';

const path=process.argv[2];
if(!path)throw new Error('Informe um arquivo local de configuração de teste.');
const config=JSON.parse(fs.readFileSync(path,'utf8'));
const environment=resolveEnvironment(config);
assert.equal(environment.isSharedTest,true);
const ids=config.deliveryIds;
assert.ok(Array.isArray(ids)&&ids.length>0&&ids.length<=5&&ids.every(Number.isSafeInteger));
assert.ok(Number.isSafeInteger(config.controlId)&&!ids.includes(config.controlId));
const client=()=>createClient(environment.url,environment.key,{global:{fetch:createSharedTestFetch(environment)},auth:{persistSession:false,autoRefreshToken:false}});
const scoped=client();
const initial=await scoped.from('entregas').select('id,cliente,status,motorista_id,ordem_logistica').in('id',ids);
if(initial.error)throw initial.error;
assert.equal(initial.data.length,ids.length);
assert.ok(initial.data.every(row=>isTestCard(row)&&row.status==='pendente'&&row.motorista_id===null));
const driver=await scoped.from('motoristas').select('id,nome,aprovado,esta_online').eq('id',environment.testDriverId).single();
if(driver.error)throw driver.error;
assert.equal(driver.data.esta_online,false);
assert.equal(driver.data.aprovado,true);
await assignPreparedRoute(scoped,{driverId:environment.testDriverId,deliveryIds:ids});
const read=async()=>{
 const result=await client().from('entregas').select('id,cliente,status,motorista_id,ordem_logistica').eq('motorista_id',environment.testDriverId).eq('status','em_rota').order('ordem_logistica');
 if(result.error)throw result.error;
 assert.deepEqual(result.data.map(row=>row.id),ids);
 return result.data;
};
await read();await read();
const blocked=await scoped.from('entregas').update({status:'concluido'}).eq('id',config.controlId).select('id');
if(blocked.error)throw blocked.error;
assert.deepEqual(blocked.data,[]);
const other=await client().from('entregas').select('id').eq('motorista_id','bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb').eq('status','em_rota');
if(other.error)throw other.error;
assert.deepEqual(other.data,[]);
const after=await scoped.from('motoristas').select('esta_online').eq('id',environment.testDriverId).single();
if(after.error)throw after.error;
assert.equal(after.data.esta_online,false);
console.log(JSON.stringify({result:'PASS',deliveryIds:ids,driverOffline:true,freshClientsReadSameRoute:true,controlUpdateBlocked:true,otherDriverReceivedNothing:true}));
